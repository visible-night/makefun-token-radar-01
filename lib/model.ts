// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// 160 pre-token protocols below the watchlist floor with the highest implied value: the early rows the
// radar exists to find. A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol). Live-token protocols are kept apart and shown with the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and its base multiple is calibrated
// from the snapshot itself: the market prices live tokens against TVL, so the model takes the median
// market-cap-to-TVL ratio of the live-token protocols, per category where the category has enough
// live protocols to speak for itself, else the global median. No protocol name is ever special-cased.
//
//   multiple     = median(mcap_usd / tvl_usd) over live-token, non-CEX protocols with a sane ratio,
//                  per category when n >= 5, else the global median; clamped to [0.05, 1.00]
//   base         = tvl_usd x multiple
//   growth       = clamp(change_7d, -50, 100) per cent
//   growthMult   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity     = 0.70 + min(age_days, 730) / 730 x 0.30   (age_days unknown: 365)
//   implied      = max(1, round(base x growthMult x maturity))
//
// The constants are the model's, stated in the dashboard and changeable in the model sandbox.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_floor: number;
  multiple_cap: number;
  min_category_n: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 730,
  unknown_age_days: 365,
  multiple_floor: 0.05,
  multiple_cap: 1.0,
  min_category_n: 5,
};

